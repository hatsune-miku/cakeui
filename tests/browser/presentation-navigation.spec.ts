import { expect, test } from '@playwright/test'

test('axis centres the selected item, animates root changes only, and respects focus and reduced motion', async ({
  page,
}) => {
  await page.goto('/tests/browser/fixtures/navigation/')
  const nav = page.getByRole('navigation')
  await expect(nav.getByRole('button')).toHaveCount(5)
  const current = nav.locator('[aria-current="step"]')
  const bounds = await nav.boundingBox()
  const selected = await current.boundingBox()
  expect(selected!.x + selected!.width / 2).toBeCloseTo(bounds!.x + bounds!.width / 2, 1)
  await current.focus()
  await page.keyboard.press('ArrowRight')
  await expect(current).toHaveText('Chapter 5')
  await expect(current).toBeFocused()
  expect(await nav.evaluate((node) => node.getAnimations({ subtree: true }).length)).toBeGreaterThan(0)
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Toggle child' }).click()
  await expect(nav).toContainText('Child page')
  expect(await nav.evaluate((node) => node.getAnimations({ subtree: true }).length)).toBe(0)
  const deck = page.getByRole('region', { name: 'Presentation', exact: true })
  await deck.focus()
  await expect(deck).toHaveCSS('outline-style', 'none')
  await page.keyboard.press('ArrowRight')
  await expect(current).toHaveText('Chapter 6')
  const text = page.getByText('Selectable chapter 6 text', { exact: true })
  await text.evaluate((node) => {
    const range = document.createRange()
    range.selectNodeContents(node)
    getSelection()!.removeAllRanges()
    getSelection()!.addRange(range)
  })
  expect(await page.evaluate(() => getSelection()!.toString())).toBe('Selectable chapter 6 text')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await nav.getByRole('button', { name: 'Chapter 7' }).click()
  expect(await nav.evaluate((node) => node.getAnimations({ subtree: true }).length)).toBe(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.emulateMedia({ media: 'print' })
  await expect(nav).toBeHidden()
})
