import { expect, test } from '@playwright/test'

async function openTextMenu(page: import('@playwright/test').Page, target: import('@playwright/test').Locator) {
  await target.scrollIntoViewIfNeeded()
  const rect = (await target.boundingBox())!
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
  await page.mouse.down({ button: 'right' })
  await expect(page.getByRole('menu', { name: 'Text color', exact: true })).toBeVisible()
  await page.mouse.up({ button: 'right' })
  return page.getByRole('menu', { name: 'Text color', exact: true })
}

test('global threshold and role rules preserve backgrounds and survive Apply/reload', async ({ page }) => {
  await page.goto('/tests/browser/fixtures/theme/')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const button = page.getByRole('button', { name: 'Default', exact: true })
  const primary = page.getByTestId('primary')
  const backgrounds = await Promise.all(
    [button, primary].map((node) => node.evaluate((element) => getComputedStyle(element).backgroundColor))
  )
  await page.getByRole('button', { name: 'Theme', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Theme settings' })
  await dialog.getByRole('radio', { name: 'Light text', exact: true }).check()
  await expect(button).toHaveCSS('color', 'rgb(255, 255, 255)')
  await dialog.getByText('Local adjustments', { exact: false }).click()
  await dialog.getByLabel('Default buttons', { exact: true }).selectOption('auto')
  await expect(button).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(primary).toHaveCSS('color', 'rgb(255, 255, 255)')
  await dialog.getByLabel('Light/dark threshold', { exact: false }).fill('100')
  await expect(button).toHaveCSS('color', 'rgb(255, 255, 255)')
  await dialog.getByRole('button', { name: 'Reset threshold', exact: true }).click()
  await expect(button).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  expect(
    await Promise.all(
      [button, primary].map((node) => node.evaluate((element) => getComputedStyle(element).backgroundColor))
    )
  ).toEqual(backgrounds)
  await dialog.getByRole('button', { name: 'Apply', exact: true }).click()
  await page.reload()
  await expect(button).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(primary).toHaveCSS('color', 'rgb(255, 255, 255)')
  await page.getByLabel('Mode', { exact: true }).selectOption('dark')
  await expect(button).toHaveCSS('color', 'rgb(255, 255, 255)')
})

test('single components use semantic regions, survive reordering and reload, and reset independently', async ({
  page,
}) => {
  await page.goto('/tests/browser/fixtures/theme/')
  const first = page.getByRole('region', { name: 'first section' }).getByRole('button')
  const second = page.getByRole('region', { name: 'second section' }).getByRole('button')
  const background = await first.evaluate((element) => getComputedStyle(element).backgroundColor)
  const menu = await openTextMenu(page, first)
  await menu.getByRole('menuitemradio', { name: 'Light', exact: true }).click()
  await expect(first).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(second).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  await menu.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Reverse sections' }).click()
  await expect(first).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(second).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  expect(await first.evaluate((element) => getComputedStyle(element).backgroundColor)).toBe(background)
  await page.reload()
  await expect(first).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(second).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  await first.focus()
  await page.keyboard.press('Alt+Shift+c')
  await expect(menu).toBeVisible()
  await menu.getByRole('menuitemradio', { name: 'Follow role', exact: true }).click()
  await expect(first).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  await page.keyboard.press('Escape')
  await expect(first).toBeFocused()
  await expect(menu).not.toBeVisible()
})

test('short right click preserves existing menus and long press does not invoke business commands', async ({
  page,
}) => {
  await page.goto('/tests/browser/fixtures/theme/')
  const target = page.getByRole('button', { name: 'Context target', exact: true })
  await target.click({ button: 'right' })
  const existing = page.getByRole('menu', { name: 'Existing actions' })
  await expect(existing).toBeVisible()
  await page.getByRole('menuitem', { name: 'Existing command' }).click()
  await expect(page.getByTestId('context-actions')).toHaveText('1')
  const menu = await openTextMenu(page, target)
  await expect(existing).not.toBeVisible()
  await expect(page.getByTestId('context-actions')).toHaveText('1')
  await menu.getByRole('menuitemradio', { name: 'Light', exact: true }).click()
  await expect(target).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(page.getByTestId('context-actions')).toHaveText('1')
})

test('same-name copies persist independently and storage failures offer retry', async ({ page }) => {
  await page.goto('/tests/browser/fixtures/theme/')
  const duplicates = page.getByRole('button', { name: 'Ambiguous action', exact: true })
  let menu = await openTextMenu(page, duplicates.first())
  await expect(menu).not.toContainText('cannot be uniquely identified')
  await menu.getByRole('menuitemradio', { name: 'Light', exact: true }).click()
  await expect(duplicates.first()).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(duplicates.last()).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  expect(await page.evaluate(() => localStorage.getItem('cake-theme-fixture'))).not.toBeNull()
  await page.reload()
  await expect(duplicates.first()).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(duplicates.last()).not.toHaveCSS('color', 'rgb(255, 255, 255)')
  await page.keyboard.press('Escape')
  await page.getByRole('checkbox', { name: 'Fail saving' }).check()
  menu = await openTextMenu(page, page.getByTestId('primary'))
  await menu.getByRole('menuitemradio', { name: 'Light', exact: true }).click()
  await expect(menu.getByRole('status')).toContainText('Could not save')
  await expect(menu.getByRole('button', { name: 'Retry' })).toBeEnabled()
  await page.keyboard.press('Escape')
  await page.getByRole('checkbox', { name: 'Fail saving' }).uncheck()
  menu = await openTextMenu(page, page.getByTestId('primary'))
  await menu.getByRole('menuitemradio', { name: 'Dark', exact: true }).click()
  await expect(menu.getByRole('status')).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId('primary')).toHaveCSS('color', 'rgb(22, 27, 34)')
})

test('component changes inside the theme editor stay in its draft and Cancel restores them', async ({ page }) => {
  await page.goto('/tests/browser/fixtures/theme/')
  await page.getByRole('button', { name: 'Theme', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Theme settings' })
  const apply = dialog.getByRole('button', { name: 'Apply', exact: true })
  const original = await apply.evaluate((element) => getComputedStyle(element).color)
  const menu = await openTextMenu(page, apply)
  await menu.getByRole('menuitemradio', { name: 'Light', exact: true }).click()
  await expect(apply).toHaveCSS('color', 'rgb(255, 255, 255)')
  expect(await page.evaluate(() => localStorage.getItem('cake-theme-fixture'))).toBeNull()
  await page.keyboard.press('Escape')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).last().click()
  await page.getByRole('button', { name: 'Theme', exact: true }).click()
  await expect(apply).toHaveCSS('color', original)
})
