for (const mode of ['light', 'dark'] as const) {
  test(`combo popup supports pointer, keyboard and dismissal in ${mode} mode`, async ({ page }) => {
    await page.goto('/')
    if (mode === 'dark') await page.getByRole('button', { name: '切换深色模式' }).click()
    const select = page.getByRole('combobox', { name: '同步方式', exact: true })
    await select.click()
    await expect(select).toHaveCSS('appearance', 'base-select')
    const manual = page.getByRole('option', { name: '手动同步', exact: true })
    await expect(manual).toBeVisible()
    await manual.click()
    await expect(select).toHaveValue('manual')
    await expect(select).toBeFocused()
    await page.keyboard.press('Space')
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    await expect(select).toHaveValue('wifi')
    await select.click()
    await page.keyboard.press('ArrowUp')
    await page.keyboard.press('Escape')
    await expect(select).toHaveValue('wifi')
    await expect(select).toBeFocused()
    await select.click()
    await page.getByRole('heading', { name: '输入与选择', exact: true }).click()
    await expect(manual).not.toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await select.click()
    await expect(manual).toBeVisible()
    const bounds = await manual.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844)
    await page.screenshot({ path: `test-results/combobox-${mode}.png` })
    await manual.click()
    await expect(select).toHaveValue('manual')
  })

  test(`no serious accessibility violations in ${mode} mode`, async ({ page }) => {
    await page.goto('/')
    if (mode === 'dark') await page.getByRole('button', { name: '切换深色模式' }).click()
    const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(result.violations).toEqual([])
    await page.getByRole('button', { name: '设计变量', exact: true }).click()
    const tokens = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(tokens.violations).toEqual([])
  })
}

