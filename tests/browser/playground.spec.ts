test('interactive menu opens on right down, depresses its trigger, and selects only on release', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByLabel('设计资源，右键或 Shift F10 打开菜单', { exact: true })
  const menu = page.getByRole('menu', { name: '文件操作' })
  await trigger.hover()
  await page.mouse.down({ button: 'right' })
  await expect(menu).toBeVisible()
  await expect(menu).toBeFocused()
  await expect(trigger).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 1)')
  await expect(menu).toHaveCSS('transform', 'none')
  const pressedBounds = await menu.boundingBox()
  const positioned = await menu.evaluate((element) => ({
    x: parseFloat(element.style.left),
    y: parseFloat(element.style.top),
  }))
  expect(pressedBounds!.x).toBeCloseTo(positioned.x, 0)
  expect(pressedBounds!.y).toBeCloseTo(positioned.y, 0)
  const copy = page.getByRole('menuitem', { name: '创建副本', exact: true })
  await copy.evaluate((element) =>
    element.addEventListener('click', () => {
      element.dataset.clickCount = String(Number(element.dataset.clickCount ?? '0') + 1)
    })
  )
  await copy.locator('.cake-menuitem-label').hover()
  await expect(page.locator('.cake-toast')).not.toBeVisible()
  await page.screenshot({ path: 'test-results/contextmenu-interactive-pressed.png' })
  await page.mouse.up({ button: 'right' })
  await expect(menu).not.toBeVisible()
  await expect(trigger).toHaveCSS('transform', 'none')
  await expect(page.locator('.cake-menuitem').filter({ hasText: '创建副本' })).toHaveAttribute('data-click-count', '1')
  await expect(page.locator('.cake-toast')).toContainText('已创建副本：设计资源 副本')
  // A late platform contextmenu must not reopen the just-selected menu.
  await trigger.evaluate((element) =>
    element.dispatchEvent(
      new MouseEvent('contextmenu', { button: 2, bubbles: true, cancelable: true, clientX: 100, clientY: 100 })
    )
  )
  await expect(menu).not.toBeVisible()
})

test('interactive release on blank space, separators or disabled items keeps the menu open', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByLabel('设计资源，右键或 Shift F10 打开菜单', { exact: true })
  const menu = page.getByRole('menu', { name: '文件操作' })
  for (const target of ['padding', 'outside', 'separator', 'disabled']) {
    await trigger.hover()
    await page.mouse.down({ button: 'right' })
    await expect(menu).toBeVisible()
    if (target === 'outside') await page.getByRole('heading', { name: '浮层与菜单', exact: true }).hover()
    if (target === 'separator') await menu.locator('.cake-menu-separator').hover()
    if (target === 'disabled') await page.getByRole('menuitem', { name: '复制共享链接' }).hover()
    await page.mouse.up({ button: 'right' })
    await expect(menu).toBeVisible()
    await expect(trigger).toHaveCSS('transform', 'none')
    await expect(page.locator('.cake-toast')).not.toBeVisible()
    await page.keyboard.press('Escape')
    await expect(menu).not.toBeVisible()
  }
  await trigger.click({ button: 'right' })
  await expect(menu).toBeVisible()
  await page.getByRole('menuitem', { name: '重命名' }).click()
  await expect(page.getByRole('dialog', { name: '重命名资源' })).toBeVisible()
  await page.keyboard.press('Escape')
  await trigger.hover()
  await page.mouse.down({ button: 'right' })
  await page.getByRole('menuitem', { name: '重命名' }).hover()
  await page.mouse.up({ button: 'right' })
  await expect(menu).not.toBeVisible()
  await expect(page.getByRole('dialog', { name: '重命名资源' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '资源名称' })).toBeFocused()
})

