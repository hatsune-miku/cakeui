  await page.reload()
  await expect(page.locator('.demo-app')).toHaveAttribute('data-theme', 'blue')
  await page.getByRole('button', { name: '切换深色模式' }).click()
  await expect(page.locator('.demo-app')).toHaveAttribute('data-mode', 'dark')
  await page.getByRole('textbox', { name: '搜索组件' }).fill('Button')
  await expect(page.locator('.demo-section')).toHaveCount(2)
  await page.getByRole('button', { name: '查看按钮与提示代码' }).click()
  await expect(page.locator('#actions .demo-code')).toContainText('<Button')
  await page.getByRole('textbox', { name: '搜索组件' }).fill('does-not-exist')
  await expect(page.getByText('没有找到「does-not-exist」相关组件。')).toBeVisible()
  await page.getByRole('button', { name: '应用示例', exact: true }).click()
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  await page.getByRole('textbox', { name: '任务名称' }).fill('测试真实任务流程')
  const category = page.getByRole('combobox', { name: '分类', exact: true })
  await category.click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '新建任务', exact: true })).toBeVisible()
  await expect(category).toBeFocused()
  await category.click()
  await page.getByRole('option', { name: '文档', exact: true }).click()
