test('dialog traps focus, dismisses on Escape, restores focus and retains theme', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '金', exact: true }).click()
  const trigger = page.getByRole('button', { name: '打开对话框' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '重命名资源' })
  await expect(dialog).toBeVisible()
  await expect(page.getByRole('textbox', { name: '资源名称' })).toBeFocused()
  for (let index = 0; index < 8; index++) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  }
  expect(await dialog.evaluate((element) => getComputedStyle(element).getPropertyValue('--cake-accent').trim())).toBe(
    '#8b654a'
  )
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.getByRole('textbox', { name: '资源名称' }).fill('新名称')
  await page.keyboard.press('Enter')
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.cake-toast')).toContainText('新名称')
})

test('context menu is clamped to viewport and supports keyboard selection', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('switch', { name: 'Interactive 模式' }).uncheck()
  const trigger = page.getByLabel('设计资源，右键或 Shift F10 打开菜单', { exact: true })
  await trigger.focus()
  await page.keyboard.press('Shift+F10')
  const menu = page.getByRole('menu', { name: '文件操作' })
  await expect(menu).toBeVisible()
  await expect(page.getByRole('menuitem', { name: '重命名' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: '创建副本' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: '移至回收站' })).toBeFocused()
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  await expect(menu).not.toBeVisible()
  await expect(page.getByRole('dialog', { name: '重命名资源' })).toBeVisible()
  await page.keyboard.press('Escape')
  await trigger.click({ button: 'right' })
  const bounds = await menu.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(1050)
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

