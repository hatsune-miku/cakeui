import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('submenu supports hover, click, keyboard scope, focus restoration and parent dismissal', async ({ page }) => {
  await page.goto('/tests/browser/fixtures/submenu/')
  await page.getByRole('button', { name: 'Open menu' }).click()
  const trigger = page.getByRole('menuitem', { name: 'Font', exact: true })
  const submenu = page.getByRole('menu', { name: 'Font choices' })
  await trigger.click()
  await expect(submenu).toBeVisible()
  await expect(page.getByRole('menuitemradio', { name: 'Default', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitemradio', { name: 'Display' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitemradio', { name: 'Default', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(submenu).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'After', exact: true })).toBeFocused()
  await trigger.focus()
  await page.keyboard.press('ArrowRight')
  await expect(submenu).toBeVisible()
  await page.keyboard.press('ArrowLeft')
  await expect(trigger).toBeFocused()
  await page.mouse.move(10, 500)
  await trigger.hover()
  await expect(submenu).toBeVisible()
  await page.getByRole('menuitemradio', { name: 'Display' }).hover()
  await page.waitForTimeout(220)
  await expect(submenu).toBeVisible()
  expect((await new AxeBuilder({ page }).include('.fixture-menu').analyze()).violations).toEqual([])
  await page.getByRole('menuitemradio', { name: 'Display' }).click()
  await expect(submenu).toHaveCount(0)
  await expect(page.locator('output')).toHaveText('Display')
  await page.getByRole('button', { name: 'Open menu' }).click()
  await trigger.focus()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Tab')
  await expect(submenu).toHaveCount(0)
  await expect(page.getByRole('menu', { name: 'Root', exact: true })).toBeHidden()
})

test('submenu flips at the edge and offers a back item when narrow screens require overlap', async ({ page }) => {
  await page.goto('/tests/browser/fixtures/submenu/')
  await page.getByRole('button', { name: 'Move root' }).click()
  await page.getByRole('button', { name: 'Open menu' }).click()
  const trigger = page.getByRole('menuitem', { name: 'Font', exact: true })
  const submenu = page.getByRole('menu', { name: 'Font choices' })
  await trigger.click()
  await expect(submenu).toHaveAttribute('data-placement', 'left')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 500 })
  await trigger.click()
  await expect(submenu).toHaveAttribute('data-placement', 'overlap')
  const bounds = await submenu.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(8)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(382)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(492)
  await page.getByRole('menuitem', { name: 'Back to root' }).click()
  await expect(submenu).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await page.evaluate(() => document.querySelector<HTMLElement>('.fixture-menu')!.hidePopover())
  await expect(submenu).toHaveCount(0)
})
