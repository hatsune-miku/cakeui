import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

import { loadThemeModule } from './theme-module.mjs'

const { themePresets, createThemeConfig, generateTheme } = await loadThemeModule()
const path = new URL('../src/theme/_generated.scss', import.meta.url)
const modes = ['light', 'dark']
const variants = themePresets.flatMap(({ id }) =>
  modes.map((mode) => ({ id, mode, theme: generateTheme(createThemeConfig({ scheme: id, mode })) }))
)
const properties = Object.keys(variants[0].theme.variables)
for (const variant of variants) assert.deepEqual(Object.keys(variant.theme.variables).sort(), [...properties].sort())
const content = await format(
  `// Generated by npm run themes:build from src/theme; do not edit.
@mixin theme($scheme, $mode) {
${variants
  .map(
    ({ id, mode, theme }) =>
      `@if $scheme == '${id}' and $mode == '${mode}' {\n${Object.entries(theme.variables)
        .map(([name, value]) => `${name}: ${value};`)
        .join('\n')}\n}`
  )
  .join('\n')}
}
@mixin configured($mode) {
${properties.map((name) => `${name}: var(--cake-config-#{$mode}-${name.slice(7)});`).join('\n')}
}
`,
  { ...(await resolveConfig(fileURLToPath(path))), parser: 'scss' }
)
if (process.argv.includes('--check'))
  assert.equal(
    readFileSync(path, 'utf8').replace(/\r\n/g, '\n'),
    content,
    'Run npm run themes:build after changing theme calculations.'
  )
else writeFileSync(path, content)
console.log(
  `Theme CSS ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${variants.length} palettes, ${properties.length} variables.`
)
